"""Scripted demonstration provider (NOT AI).

Exercises the propose -> review -> approve -> retest workflow without an AI provider by
returning pre-written patches shipped in ``examples/demo-fixes/<repository>/``. It only
works for the bundled example repositories, and every result it produces is recorded
with ``is_ai = false`` and labelled as scripted in the UI.
"""

from __future__ import annotations

import json
from pathlib import Path

from devflow.ai.base import AnalysisInput, AnalysisOutput, ProviderError
from devflow.runners.base import Availability


class DemoProvider:
    name = "demo"
    label = "Scripted demo patches (not AI)"
    is_ai = False
    generates_patches = True

    def __init__(self, fixes_dir: Path) -> None:
        self.fixes_dir = fixes_dir

    def availability(self) -> Availability:
        if not self.fixes_dir.is_dir():
            return Availability(False, "demo fixes directory missing")
        return Availability(True, "bundled example repositories only")

    def analyze(self, request: AnalysisInput, workspace: Path) -> AnalysisOutput:
        manifest_path = self.fixes_dir / request.repository_name / "manifest.json"
        if not request.is_example or not manifest_path.is_file():
            raise ProviderError(
                "The scripted demo provider only supports bundled example repositories"
            )
        manifest = json.loads(manifest_path.read_text())
        failing = [f.nodeid or "" for f in request.failures]
        chosen = [
            entry
            for entry in manifest["patches"]
            if any(node.startswith(prefix) for node in failing for prefix in entry["test_prefixes"])
        ]
        if not chosen:
            return AnalysisOutput(
                "No scripted fix matches these failures",
                "[SCRIPTED DEMO - NOT AI] The demo manifest has no patch for the failing tests.",
            )
        diff = "".join((manifest_path.parent / entry["patch"]).read_text() for entry in chosen)
        return AnalysisOutput(
            root_cause="[SCRIPTED DEMO - NOT AI] " + " ".join(e["root_cause"] for e in chosen),
            explanation="This diagnosis and patch were written in advance for the bundled example "
            "repository to demonstrate the review workflow. They were not generated by an AI model.",
            confidence="high",
            patch=diff,
            patch_rationale=" ".join(e["rationale"] for e in chosen),
        )
